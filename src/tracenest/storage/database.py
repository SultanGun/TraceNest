"""Local SQLite database manager for TraceNest snapshots and sessions."""

import json
import sqlite3
from pathlib import Path
from typing import List

from tracenest.exceptions import (
    DatabaseCorruptionError,
    SessionNotFoundError,
    SnapshotNotFoundError,
    StorageError,
)
from tracenest.models import (
    ChangeType,
    FileChange,
    Finding,
    FindingSeverity,
    SessionMetadata,
    Snapshot,
)
from tracenest.scanners.secrets import redact_text
from tracenest.storage.migrations import apply_migrations


def ensure_storage_dir(repo_root: Path, dir_name: str = ".tracenest") -> Path:
    """Ensure project storage directory exists with an internal .gitignore."""
    storage_dir = repo_root / dir_name
    storage_dir.mkdir(parents=True, exist_ok=True)

    git_ignore_file = storage_dir / ".gitignore"
    if not git_ignore_file.exists():
        git_ignore_file.write_text("# Automatically generated by TraceNest\n*\n", encoding="utf-8")

    return storage_dir


class Database:
    """Encapsulates SQLite operations for snapshots, sessions, diffs, and findings."""

    def __init__(self, db_path: Path):
        self.db_path = db_path
        self._init_db()

    def _get_connection(self) -> sqlite3.Connection:
        try:
            conn = sqlite3.connect(str(self.db_path), timeout=10.0)
            conn.row_factory = sqlite3.Row
            conn.execute("PRAGMA foreign_keys = ON")
            return conn
        except sqlite3.DatabaseError as e:
            raise DatabaseCorruptionError(f"Database at {self.db_path} is corrupted: {e}")

    def _init_db(self) -> None:
        """Run database migrations and verify schema version."""
        try:
            with self._get_connection() as conn:
                apply_migrations(conn)
        except sqlite3.DatabaseError as e:
            raise DatabaseCorruptionError(f"Failed to initialize database: {e}")

    def save_snapshot(self, snapshot: Snapshot) -> None:
        """Persist a baseline snapshot."""
        query = """
        INSERT OR REPLACE INTO snapshots (
            snapshot_id, created_at, repo_root, git_commit, git_branch,
            label, note, working_tree_fingerprint, file_count
        ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
        """
        try:
            with self._get_connection() as conn:
                conn.execute(
                    query,
                    (
                        snapshot.snapshot_id,
                        snapshot.created_at,
                        snapshot.repo_root,
                        snapshot.git_commit,
                        snapshot.git_branch,
                        snapshot.label,
                        snapshot.note,
                        snapshot.working_tree_fingerprint,
                        snapshot.file_count,
                    ),
                )
                conn.commit()
        except sqlite3.Error as e:
            raise StorageError(f"Failed to save snapshot {snapshot.snapshot_id}: {e}")

    def get_snapshot(self, snapshot_id: str) -> Snapshot:
        """Retrieve a snapshot by ID."""
        query = "SELECT * FROM snapshots WHERE snapshot_id = ?"
        try:
            with self._get_connection() as conn:
                cur = conn.execute(query, (snapshot_id,))
                row = cur.fetchone()
                if not row:
                    raise SnapshotNotFoundError(f"Snapshot '{snapshot_id}' not found.")
                return Snapshot(
                    snapshot_id=row["snapshot_id"],
                    created_at=row["created_at"],
                    repo_root=row["repo_root"],
                    git_commit=row["git_commit"],
                    git_branch=row["git_branch"],
                    label=row["label"],
                    note=row["note"],
                    working_tree_fingerprint=row["working_tree_fingerprint"],
                    file_count=row["file_count"],
                )
        except SnapshotNotFoundError:
            raise
        except sqlite3.Error as e:
            raise StorageError(f"Failed to load snapshot {snapshot_id}: {e}")

    def list_snapshots(self, limit: int = 100) -> List[Snapshot]:
        """List snapshots ordered by creation time descending."""
        query = "SELECT * FROM snapshots ORDER BY created_at DESC LIMIT ?"
        try:
            with self._get_connection() as conn:
                cur = conn.execute(query, (limit,))
                results = []
                for row in cur.fetchall():
                    results.append(
                        Snapshot(
                            snapshot_id=row["snapshot_id"],
                            created_at=row["created_at"],
                            repo_root=row["repo_root"],
                            git_commit=row["git_commit"],
                            git_branch=row["git_branch"],
                            label=row["label"],
                            note=row["note"],
                            working_tree_fingerprint=row["working_tree_fingerprint"],
                            file_count=row["file_count"],
                        )
                    )
                return results
        except sqlite3.Error as e:
            raise StorageError(f"Failed to list snapshots: {e}")

    def save_session(self, session: SessionMetadata) -> None:
        """Persist a complete review session, including file changes and findings."""
        insert_sess = """
        INSERT OR REPLACE INTO sessions (
            session_id, created_at, repo_root, repo_id, baseline_ref,
            comparison_method, status, labels_json, notes, ai_summary,
            test_status, report_paths_json
        ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        """
        insert_change = """
        INSERT INTO file_changes (
            session_id, path, old_path, change_type, additions, deletions,
            is_binary, size_bytes, diff_text, old_hash, new_hash
        ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        """
        insert_finding = """
        INSERT INTO findings (
            session_id, finding_id, rule_id, severity, title, explanation,
            file_path, line_number, evidence, recommendation, confidence
        ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        """

        try:
            with self._get_connection() as conn:
                conn.execute(
                    insert_sess,
                    (
                        session.session_id,
                        session.created_at,
                        session.repo_root,
                        session.repo_id,
                        session.baseline_ref,
                        session.comparison_method,
                        session.status,
                        json.dumps(session.labels),
                        session.notes,
                        session.ai_summary,
                        session.test_status,
                        json.dumps(session.report_paths),
                    ),
                )
                # Remove existing child rows if updating
                conn.execute("DELETE FROM file_changes WHERE session_id = ?", (session.session_id,))
                conn.execute("DELETE FROM findings WHERE session_id = ?", (session.session_id,))

                for change in session.file_changes:
                    safe_diff = redact_text(change.diff_text) if change.diff_text else None
                    conn.execute(
                        insert_change,
                        (
                            session.session_id,
                            change.path,
                            change.old_path,
                            change.change_type.value,
                            change.additions,
                            change.deletions,
                            1 if change.is_binary else 0,
                            change.size_bytes,
                            safe_diff,
                            change.old_hash,
                            change.new_hash,
                        ),
                    )

                for finding in session.findings:
                    conn.execute(
                        insert_finding,
                        (
                            session.session_id,
                            finding.finding_id,
                            finding.rule_id,
                            finding.severity.value,
                            finding.title,
                            finding.explanation,
                            finding.file_path,
                            finding.line_number,
                            finding.evidence,
                            finding.recommendation,
                            finding.confidence,
                        ),
                    )

                conn.commit()
        except sqlite3.Error as e:
            raise StorageError(f"Failed to save session {session.session_id}: {e}")

    def get_session(self, session_id: str) -> SessionMetadata:
        """Retrieve a session with all its file changes and findings."""
        try:
            with self._get_connection() as conn:
                cur = conn.execute("SELECT * FROM sessions WHERE session_id = ?", (session_id,))
                row = cur.fetchone()
                if not row:
                    raise SessionNotFoundError(f"Session '{session_id}' not found.")

                # Load changes
                cur_changes = conn.execute(
                    "SELECT * FROM file_changes WHERE session_id = ? ORDER BY path",
                    (session_id,),
                )
                file_changes = [
                    FileChange(
                        path=r["path"],
                        old_path=r["old_path"],
                        change_type=ChangeType(r["change_type"]),
                        additions=r["additions"],
                        deletions=r["deletions"],
                        is_binary=bool(r["is_binary"]),
                        size_bytes=r["size_bytes"],
                        diff_text=r["diff_text"],
                        old_hash=r["old_hash"],
                        new_hash=r["new_hash"],
                    )
                    for r in cur_changes.fetchall()
                ]

                # Load findings
                cur_findings = conn.execute(
                    "SELECT * FROM findings WHERE session_id = ?",
                    (session_id,),
                )
                findings = [
                    Finding(
                        finding_id=r["finding_id"],
                        rule_id=r["rule_id"],
                        severity=FindingSeverity(r["severity"]),
                        title=r["title"],
                        explanation=r["explanation"],
                        file_path=r["file_path"],
                        line_number=r["line_number"],
                        evidence=r["evidence"],
                        recommendation=r["recommendation"],
                        confidence=r["confidence"],
                    )
                    for r in cur_findings.fetchall()
                ]

                return SessionMetadata(
                    session_id=row["session_id"],
                    created_at=row["created_at"],
                    repo_root=row["repo_root"],
                    repo_id=row["repo_id"],
                    baseline_ref=row["baseline_ref"],
                    comparison_method=row["comparison_method"],
                    status=row["status"],
                    file_changes=file_changes,
                    findings=findings,
                    labels=json.loads(row["labels_json"]),
                    notes=row["notes"],
                    ai_summary=row["ai_summary"],
                    test_status=row["test_status"],
                    report_paths=json.loads(row["report_paths_json"]),
                )
        except SessionNotFoundError:
            raise
        except sqlite3.Error as e:
            raise StorageError(f"Failed to load session {session_id}: {e}")

    def list_sessions(self, limit: int = 50) -> List[SessionMetadata]:
        """List sessions ordered by creation timestamp descending."""
        try:
            with self._get_connection() as conn:
                cur = conn.execute(
                    "SELECT session_id FROM sessions ORDER BY created_at DESC LIMIT ?",
                    (limit,),
                )
                session_ids = [r["session_id"] for r in cur.fetchall()]
            return [self.get_session(sid) for sid in session_ids]
        except sqlite3.Error as e:
            raise StorageError(f"Failed to list sessions: {e}")
