"""Markdown and JSON report generators for review sessions."""

import json
from collections import Counter
from pathlib import Path
from typing import Any, Dict, Optional

from tracenest.models import FindingSeverity, SessionMetadata

REPORT_SCHEMA_VERSION = "tracenest-report-v1"


def generate_markdown_report(session: SessionMetadata) -> str:
    """Format session review into a GitHub-flavored Markdown document."""
    # Compute change statistics
    total_files = len(session.file_changes)
    total_adds = sum(c.additions for c in session.file_changes)
    total_dels = sum(c.deletions for c in session.file_changes)

    # Compute findings severity breakdown
    severity_counts = Counter(f.severity for f in session.findings)
    crit_count = severity_counts.get(FindingSeverity.CRITICAL, 0)
    high_count = severity_counts.get(FindingSeverity.HIGH, 0)
    med_count = severity_counts.get(FindingSeverity.MEDIUM, 0)
    low_count = severity_counts.get(FindingSeverity.LOW, 0)
    info_count = severity_counts.get(FindingSeverity.INFO, 0)
    total_findings = len(session.findings)

    # Format Changed Files Table
    files_table_rows = []
    if session.file_changes:
        for c in session.file_changes:
            bin_flag = " (binary)" if c.is_binary else ""
            old_str = f" (renamed from `{c.old_path}`)" if c.old_path else ""
            files_table_rows.append(
                f"| `{c.path}`{old_str} | {c.change_type.value}{bin_flag} | +{c.additions} | -{c.deletions} |"
            )
    else:
        files_table_rows.append("| *No file changes detected* | - | 0 | 0 |")

    files_table = "\n".join(files_table_rows)

    # Format Findings
    findings_blocks = []
    if session.findings:
        for f in session.findings:
            loc = f"`{f.file_path}:{f.line_number}`" if f.line_number else f"`{f.file_path}`"
            evidence_snippet = (
                f"```\n{f.evidence}\n```" if f.evidence else "*No code excerpt available*"
            )
            findings_blocks.append(
                f"### [{f.severity.value}] {f.title} ({f.rule_id})\n\n"
                f"- **Location:** {loc}\n"
                f"- **Finding ID:** `{f.finding_id}`\n"
                f"- **Confidence:** {f.confidence}\n"
                f"- **Explanation:** {f.explanation}\n\n"
                f"**Evidence:**\n{evidence_snippet}\n\n"
                f"**Recommendation:** {f.recommendation}\n"
            )
    else:
        findings_blocks.append(
            "*No security or policy violations detected by deterministic rules.*"
        )

    findings_content = "\n\n".join(findings_blocks)

    # Format AI section
    if session.ai_summary:
        ai_section = (
            "## 🤖 AI-Assisted Advisory Explanation\n\n"
            "> [!NOTE]\n"
            "> The following summary was generated by an AI model. AI-generated commentary is "
            "advisory and untrusted. All critical determinations should be verified against deterministic evidence above.\n\n"
            f"{session.ai_summary}\n"
        )
    else:
        ai_section = (
            "## 🤖 AI-Assisted Advisory Explanation\n\n"
            "*AI assistance was not enabled for this session (running in deterministic privacy mode).*\n"
        )

    # Test status
    test_str = session.test_status if session.test_status else "Not executed during this session"

    report = f"""# TraceNest Review Report

## Session Metadata

| Property | Value |
| :--- | :--- |
| **Session ID** | `{session.session_id}` |
| **Created (UTC)** | `{session.created_at}` |
| **Repository Root** | `{session.repo_root}` |
| **Repository ID** | `{session.repo_id}` |
| **Baseline Ref** | `{session.baseline_ref}` |
| **Comparison Method** | `{session.comparison_method}` |
| **Status** | `{session.status}` |
| **Automated Tests** | {test_str} |

## Change Overview

| Metric | Count |
| :--- | :--- |
| **Changed Files** | {total_files} |
| **Lines Added** | +{total_adds} |
| **Lines Deleted** | -{total_dels} |
| **Total Findings** | {total_findings} (Critical: {crit_count}, High: {high_count}, Medium: {med_count}, Low: {low_count}, Info: {info_count}) |

### Changed Files

| File Path | Status | Added | Deleted |
| :--- | :--- | :--- | :--- |
{files_table}

## Deterministic Review Findings

{findings_content}

{ai_section}

## Suggested Manual Verification Steps

1. Verify that all newly introduced dependencies are genuine and strictly pinned.
2. Ensure no test secrets or staging credentials were substituted in configuration files.
3. If dynamic code execution or subprocess invocations were modified, trace all inputs from boundary callers.
4. Execute the project's test suite to ensure functional correctness.

---
*Analysis Disclaimer: TraceNest provides heuristic scanning and deterministic rule evaluation. It does not replace code reviews or guarantee complete vulnerability detection.*
"""
    return report


def generate_json_report(session: SessionMetadata) -> str:
    """Format session review into structured JSON matching the documented schema."""
    data: Dict[str, Any] = {
        "$schema_version": REPORT_SCHEMA_VERSION,
        "session": {
            "session_id": session.session_id,
            "created_at": session.created_at,
            "repo_root": session.repo_root,
            "repo_id": session.repo_id,
            "baseline_ref": session.baseline_ref,
            "comparison_method": session.comparison_method,
            "status": session.status,
            "labels": session.labels,
            "notes": session.notes,
            "test_status": session.test_status,
        },
        "metrics": {
            "files_changed_count": len(session.file_changes),
            "lines_added": sum(c.additions for c in session.file_changes),
            "lines_deleted": sum(c.deletions for c in session.file_changes),
            "findings_count": len(session.findings),
            "findings_by_severity": {
                "CRITICAL": sum(
                    1 for f in session.findings if f.severity == FindingSeverity.CRITICAL
                ),
                "HIGH": sum(1 for f in session.findings if f.severity == FindingSeverity.HIGH),
                "MEDIUM": sum(1 for f in session.findings if f.severity == FindingSeverity.MEDIUM),
                "LOW": sum(1 for f in session.findings if f.severity == FindingSeverity.LOW),
                "INFO": sum(1 for f in session.findings if f.severity == FindingSeverity.INFO),
            },
        },
        "file_changes": [c.model_dump() for c in session.file_changes],
        "findings": [f.model_dump() for f in session.findings],
        "ai_summary": session.ai_summary,
        "disclaimer": (
            "TraceNest provides deterministic heuristic scanning. "
            "It does not guarantee complete security or vulnerability absence."
        ),
    }
    return json.dumps(data, indent=2, ensure_ascii=False)


def save_reports(
    session: SessionMetadata,
    output_dir: Path,
    formats: Optional[list[str]] = None,
) -> Dict[str, str]:
    """Save reports to disk in requested formats and return paths."""
    output_dir.mkdir(parents=True, exist_ok=True)
    target_formats = formats or ["markdown", "json"]
    paths = {}

    if "markdown" in target_formats or "md" in target_formats:
        md_content = generate_markdown_report(session)
        md_file = output_dir / f"report_{session.session_id}.md"
        md_file.write_text(md_content, encoding="utf-8")
        paths["markdown"] = str(md_file)

    if "json" in target_formats:
        json_content = generate_json_report(session)
        json_file = output_dir / f"report_{session.session_id}.json"
        json_file.write_text(json_content, encoding="utf-8")
        paths["json"] = str(json_file)

    session.report_paths.update(paths)
    return paths
